import { Code } from '@mantine/core';
import type { Route } from 'next';
import { PRODUCT_NAME } from '~/app/config';
import { CodeBlock } from '~/components/CodeBlock';
import { InternalLink } from '~/components/InternalLink';
import { PageNavigation } from '~/components/PageNavigation';
import { PageSubtitle } from '~/components/PageSubtitle';
import { PageTitle } from '~/components/PageTitle';
import { Txt } from '~/components/Txt';
import { UnorderedList } from '~/components/UnorderedList';
import { readCodeFile } from '~/lib/code';
import { allPromiseProps, getRouteMetadata } from '~/lib/utils';
import { BasicUsageExample } from './BasicUsageExample';
import { BasicUsageNestedPropertiesExample } from './BasicUsageNestedPropertiesExample';

const PATH: Route = '/examples/basic-usage';

export const metadata = getRouteMetadata(PATH);

export default async function BasicUsageExamplePage() {
  const code = await allPromiseProps({
    'BasicUsageExample.tsx': readCodeFile<string>(`${PATH}/BasicUsageExample.tsx`),
    'companies.json': readCodeFile<string>('/../data/companies.json'),
    nested: readCodeFile<string>(`${PATH}/BasicUsageNestedPropertiesExample.tsx`),
  });

  return (
    <>
      <PageTitle of={PATH} />
      <Txt>
        In its most basic usage scenario, the DataTable component only requires the <Code>records</Code> and{' '}
        <Code>columns</Code> properties to be set:
      </Txt>
      <CodeBlock tabs={{ code, keys: ['BasicUsageExample.tsx', 'companies.json'] }} />
      <Txt>The code above will produce the following result:</Txt>
      <BasicUsageExample />
      <Txt>A few things worth noting:</Txt>
      <UnorderedList>
        <li>
          each column’s <Code>accessor</Code> tells the component which record property to display in that column;
        </li>
        <li>
          when a column doesn’t have a <Code>title</Code>, one is generated by “humanizing” its accessor (i.e.{' '}
          <Code>streetAddress</Code> becomes <em>Street address</em>);
        </li>
        <li>
          each record must have a unique <Code>id</Code> property, which is used as the row key; if your records are
          identified by a different property, have a look at the{' '}
          <InternalLink to="/examples/non-standard-record-ids">non-standard record IDs</InternalLink> example.
        </li>
      </UnorderedList>
      <PageSubtitle value="Displaying nested properties" />
      <Txt>
        Accessors support dot-notation, so you can display nested object properties without writing a custom{' '}
        <Code>render</Code> function:
      </Txt>
      <CodeBlock code={code.nested} />
      <BasicUsageNestedPropertiesExample />
      <Txt>
        However, there’s much more you can do with {PRODUCT_NAME}. Head over to the next example to learn about its
        basic properties.
      </Txt>
      <PageNavigation of={PATH} />
    </>
  );
}
